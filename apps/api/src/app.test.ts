import { HTTPException } from 'hono/http-exception';
import { describe, expect, test } from 'vitest';

import { testApp, testConfig } from '../test/app.ts';
import { makeUser } from '../test/factories/user.ts';
import { postJson } from '../test/http.ts';

describe('GET /api/health', () => {
  test('answers 200 with the version once the database is migrated', async () => {
    const { app } = testApp();

    const response = await app.request('/api/health');

    expect(response.status).toBe(200);
    expect(await response.json()).toEqual({ status: 'ok', version: testConfig.appVersion });
  });
});

describe('every response', () => {
  test('carries the app version, a request id and the secure headers, even a 404', async () => {
    const { app } = testApp();

    const response = await app.request('/api/nowhere');

    expect(response.status).toBe(404);
    expect(response.headers.get('X-App-Version')).toBe(testConfig.appVersion);
    expect(response.headers.get('X-Request-Id')).toMatch(/^[\w-]+$/);
  });

  test('the request id is generated by the API, never taken from the client', async () => {
    const { app } = testApp();

    const response = await app.request('/api/health', { headers: { 'X-Request-Id': 'forged' } });

    expect(response.headers.get('X-Request-Id')).not.toBe('forged');
    expect(response.headers.get('X-Content-Type-Options')).toBe('nosniff');
    expect(response.headers.get('X-Frame-Options')).toBe('SAMEORIGIN');
  });

  test('a form posted from another origin is refused before reaching any route', async () => {
    const { app } = testApp();
    const post = (origin: string) =>
      app.request('/api/nowhere', {
        method: 'POST',
        headers: { Origin: origin, 'Content-Type': 'application/x-www-form-urlencoded' },
        body: 'a=1',
      });

    expect((await post('https://evil.example')).status).toBe(403);
    expect((await post('https://app.battlecrm.test')).status).toBe(404);
  });
});

describe('request log', () => {
  test('writes one JSON line per request, with the route template and the request id', async () => {
    const { app, logs } = testApp();

    const response = await app.request('/api/health');

    expect(logs()).toEqual([
      expect.objectContaining({
        level: 30,
        msg: 'request',
        method: 'GET',
        route: '/api/health',
        status: 200,
        durationMs: expect.any(Number),
        requestId: response.headers.get('X-Request-Id'),
      }),
    ]);
  });

  test('never contains passwords, tokens, cookies, Authorization or bodies', async () => {
    const { app, logger, output } = testApp();
    const secrets = [
      'hunter2-password',
      'session-token',
      'cookie-value',
      'bearer-token',
      'body-content',
    ];

    await app.request('/api/nowhere?token=session-token', {
      method: 'POST',
      headers: {
        Origin: 'https://app.battlecrm.test',
        Authorization: 'Bearer bearer-token',
        Cookie: '__Secure-session=cookie-value',
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ password: 'hunter2-password', note: 'body-content' }),
    });
    // What a careless handler could log: redact still removes it.
    logger.info({
      password: 'hunter2-password',
      user: { token: 'session-token', newPassword: 'hunter2-password' },
      headers: { authorization: 'Bearer bearer-token', cookie: 'cookie-value' },
      body: 'body-content',
    });

    for (const secret of secrets) expect(output()).not.toContain(secret);
  });
});

describe('an unexpected exception in a route', () => {
  test('answers 500, is logged with its request id and alerts down without body or user content', async () => {
    const { app, alert, logs } = testApp();
    app.post('/contacts/:id/boom', () => {
      throw new TypeError('cannot read the note of Jane Doe');
    });

    const response = await app.request('/api/contacts/42/boom?name=Jane', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ note: 'Jane Doe' }),
    });

    expect(response.status).toBe(500);
    expect(await response.json()).toEqual({ error: 'internal' });
    expect(alert.downs).toEqual(['TypeError in POST /api/contacts/:id/boom']);
    expect(logs()).toContainEqual(
      expect.objectContaining({
        level: 50,
        msg: 'unexpected error',
        requestId: response.headers.get('X-Request-Id'),
      }),
    );
  });

  test('an expected refusal does not alert', async () => {
    const { app, alert } = testApp();
    app.get('/forbidden', () => {
      throw new HTTPException(403);
    });

    expect((await app.request('/api/forbidden')).status).toBe(403);
    expect((await app.request('/api/nowhere')).status).toBe(404);
    expect(alert.downs).toEqual([]);
  });
});

async function reportClientError(body: unknown) {
  const harness = testApp();
  const { cookie, userId } = await makeUser(harness);
  const response = await postJson(harness.app, '/api/client-errors', body, cookie);
  return { response, userId, alert: harness.alert, logs: harness.logs };
}

describe('POST /api/client-errors', () => {
  test('requires a session: without one, nothing is logged and nothing alerts', async () => {
    const { app, alert, logs } = testApp();

    const response = await postJson(app, '/api/client-errors', {
      message: 'x is undefined',
      version: '1.2.3',
    });

    expect(response.status).toBe(401);
    expect(alert.downs).toEqual([]);
    expect(logs()).not.toContainEqual(expect.objectContaining({ msg: 'client error' }));
  });

  test('logs the message, the stack and the version of the SPA, then alerts down', async () => {
    const { response, alert, logs } = await reportClientError({
      message: 'x is undefined',
      stack: 'TypeError: x is undefined\n    at render (app.js:1:2)',
      version: '1.2.3',
    });

    expect(response.status).toBe(204);
    expect(logs()).toContainEqual(
      expect.objectContaining({
        level: 50,
        msg: 'client error',
        clientError: {
          message: 'x is undefined',
          stack: 'TypeError: x is undefined\n    at render (app.js:1:2)',
          version: '1.2.3',
        },
        requestId: response.headers.get('X-Request-Id'),
      }),
    );
    expect(alert.downs).toEqual(['browser error']);
  });

  test('accepts a report without a stack', async () => {
    const { response, alert } = await reportClientError({
      message: 'Script error.',
      version: '1.2.3',
    });

    expect(response.status).toBe(204);
    expect(alert.downs).toEqual(['browser error']);
  });

  test('refuses anything else without logging it nor alerting', async () => {
    for (const body of [{ message: 'no version' }, { message: 42, version: '1.2.3' }, 'not json']) {
      const { response, alert, logs } = await reportClientError(body);

      expect(response.status).toBe(400);
      expect(alert.downs).toEqual([]);
      expect(logs()).not.toContainEqual(expect.objectContaining({ msg: 'client error' }));
    }
  });

  test('accepts the longest report, even in characters of several bytes', async () => {
    const { response } = await reportClientError({
      message: 'é'.repeat(2_000),
      stack: '€'.repeat(20_000),
      version: '1.2.3',
    });

    expect(response.status).toBe(204);
  });

  test('refuses an oversized report', async () => {
    const { response, alert } = await reportClientError({
      message: 'x'.repeat(200_000),
      version: '1.2.3',
    });

    expect(response.status).toBe(413);
    expect(alert.downs).toEqual([]);
  });
});
